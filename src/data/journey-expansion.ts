import type { JourneyNode, PersonJourney, Source } from '../types'
import { bookSource, webSource } from './expansion-kit'

type Stop = [
  string,
  number,
  string,
  [number, number],
  JourneyNode['kind'],
  string,
  string,
  Source[],
  string?,
]
function journey(personId: string, introduction: string, stops: Stop[]): PersonJourney {
  return {
    personId,
    introduction,
    nodes: stops.map(
      ([key, year, location, coordinates, kind, title, summary, sources, dateNote]) => ({
        id: `${personId}-record-${key}`,
        year,
        location,
        coordinates,
        kind,
        title,
        summary,
        sources,
        locationNote:
          '坐标为所述城市、寺院所在地区或山地的阅读参照，未测绘当时建筑边界和中间行路。',
        ...(dateNote ? { dateNote } : {}),
      }),
    ),
  }
}
