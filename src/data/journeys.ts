function node(
  person: string,
  key: string,
  year: number,
  location: string,
  coordinates: [number, number],
  kind: JourneyNode['kind'],
  title: string,
  summary: string,
  source: Source,
  dateNote?: string,
  locationNote = cityNote,
): JourneyNode {
  return {
    id: `${person}-${key}`,
    year,
    location,
    coordinates,
    kind,
    title,
    summary,
    sources: [source],
    locationNote,
    ...(dateNote ? { dateNote } : {}),
  }
}
