export function createExpandedEvents(people: Person[]): HistoryEvent[] {
  const byName = new Map<string, string>()
  for (const person of people)
    for (const name of [person.name, ...(person.aliases ?? [])])
      if (!byName.has(name)) byName.set(name, person.id)
  for (const person of people) byName.set(person.name, person.id)
  const drafts = [
    ...additions,
    ...foundations.map(([id, title, coordinates, names]) => {
      const dynasty = dynasties.find((dynasty) => dynasty.id === id)!
      return e(
        `foundation-${id}`,
        dynasty.from,
        title,
        '政治',
        dynasty.capital,
        coordinates,
        `${title}，新的政权以${dynasty.capital}等地为政治中心。`,
        dynasty.context,
        dynasty.summary,
        names,
        dynasty.sources,
        4,
        dynasty.dateNote ? { dateNote: dynasty.dateNote } : undefined,
      )
    }),
  ]
  return drafts.map(({ names, ...event }) => ({
    ...event,
    people: names.map((name) => {
      const id = byName.get(name)
      if (!id) throw new Error(`Missing sourced person: ${event.id} → ${name}`)
      return id
    }),
  }))
}
