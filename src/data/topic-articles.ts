export function deepenTopics(topics: Tour[]): Tour[] {
  return topics.map((topic) => {
    const article = topicArticles[topic.id]
    if (!article) return topic
    return {
      ...topic,
      subject: article.subject,
      conclusion: article.conclusion,
      article: {
        paragraphs: article.paragraphs,
        eventIds: [...topic.steps],
        mapStops: mapStops[topic.id],
      },
    }
  })
}
