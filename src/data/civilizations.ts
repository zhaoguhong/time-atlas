import type { HistoryEvent, Source } from '../types'

const unesco = (id: number, name: string): Source => ({
  title: `UNESCO · ${name}`,
  url: `https://whc.unesco.org/en/list/${id}/`,
})
const source = (title: string, url: string): Source => ({ title, url })
const approximateBP =
  '来源以“距今”概括年代；轴上采用取整的公元前年份作浏览参照，不作逐年精确换算，也不将区间端点当作始建或废弃年份。'
function site(
  id: string,
  year: number,
  endYear: number | undefined,
  title: string,
  location: string,
  coordinates: [number, number],
  summary: string,
  details: string,
  background: string,
  impact: string,
  reference: Source,
  extra: Partial<HistoryEvent> = {},
): HistoryEvent {
  return {
    id,
    year,
    endYear,
    title,
    location,
    coordinates,
    summary,
    details: [details],
    background,
    impact,
    sources: [reference],
    people: [],
    category: '社会',
    importance: 5,
    dateLabel: `约公元前${-year}年${endYear ? `—前${-endYear}年` : ''}`,
    dateNote: '考古年代为概括区间，起点不是精确建成年，终点也不表示某一年突然消失。',
    locationNote: '坐标定位代表遗址或城市附近，不表示考古文化分布范围、古河道或国家疆界。',
    ...extra,
  }
}

