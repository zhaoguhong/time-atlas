export function createDepthEvents(people: Person[]): HistoryEvent[] {
  return depthEventDrafts.map(({ names, ...event }) => ({
    ...event,
    people: [...new Set([...names, ...(extraParticipants[event.id] ?? [])])].map((name) => {
      const person = people.find((person) => person.name === name || person.aliases?.includes(name))
      if (!person) throw new Error(`Missing person: ${event.id} → ${name}`)
      return person.id
    }),
  }))
}
