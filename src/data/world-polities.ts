type ReferenceKey = keyof typeof references

function profile(
  id: string,
  name: string,
  mapNames: string[],
  from: number,
  to: number,
  capital: string,
  summary: string,
  context: string,
  reading: string,
  sourceKeys: ReferenceKey[],
  dateNote = '阅读采用常见历史分期；地图轮廓沿用原始资料的采样年份与概略边界，两者不能相互替代。',
): WorldPolity {
  return {
    id: `world-${id}`,
    name,
    region: regions[id],
    aliases: [...new Set([name, ...mapNames])],
    mapNames,
    from,
    to,
    capital,
    summary,
    context,
    sections: [{ title: '', text: reading }],
    sources: sourceKeys.map((key) => references[key]),
    dateNote,
  }
}

