const byMapName = new Map<string, WorldPolity[]>()
for (const polity of worldPolities) {
  for (const name of polity.mapNames) {
    const matches = byMapName.get(name) ?? []
    matches.push(polity)
    byMapName.set(name, matches)
  }
}

/** Exact upstream aliases only, with a separate editorial date gate. */
export function worldPolityForMap(name: string, year: number): WorldPolity | undefined {
  return byMapName.get(name)?.find((polity) => polity.from <= year && polity.to >= year)
}

