export function enrichEventReading(events: HistoryEvent[]): HistoryEvent[] {
  return events.map((event) => {
    const explicit =
      readings[event.id] ??
      middleEventReading[event.id] ??
      lateEventReading[event.id] ??
      addedEventReading[event.id]
    const dynasty = event.id.startsWith('foundation-')
      ? dynasties.find((d) => d.id === event.id.replace('foundation-', ''))
      : undefined
    const chapter = topicTours
      .flatMap((topic) => topic.chapters ?? [])
      .find((chapter) => chapter.eventId === event.id)
    const source = primaryReferences[event.id]
    return {
      ...event,
      aliases: eventAliases[event.id] ?? event.aliases,
      sources: source
        ? [{ title: `《${source[0]}》卷${source[1]}`, url: bookUrl(...source) }, ...event.sources]
        : event.sources,
      details:
        explicit ??
        (dynasty?.sections
          ? dynasty.sections.map((section) => section.text)
          : chapter
            ? [chapter.explanation]
            : event.details),
    }
  })
}
