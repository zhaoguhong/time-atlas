export function enrichPersonReading(people: Person[]): Person[] {
  return people.map((person) => {
    const paragraphs = biographies[person.name]
    if (!paragraphs) return person
    const volume = volumes[person.name]
    const extra = volume
      ? [
          {
            title: `《${volume[0]}》卷${Number(volume[1].replace(/\D/g, ''))}`,
            url: bookUrl(...volume),
          },
        ]
      : person.name === '康熙帝'
        ? [
            {
              title: '故宫博物院 · 康熙皇帝大事年表',
              url: 'https://www.dpm.org.cn/court/lineage/226256.html',
            },
          ]
        : person.name === '玄奘'
          ? [{ title: '大唐大慈恩寺三藏法师传', url: bookUrl('大唐大慈恩寺三藏法師傳') }]
          : []
    return {
      ...person,
      biography: paragraphs.join('\n\n'),
      recordKind: 'curated',
      sources: [...extra, ...person.sources],
    }
  })
}
