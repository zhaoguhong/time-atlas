import type { JourneyNode, PersonJourney, Source } from '../types'
import { bookSource, webSource } from './expansion-kit'

type Stop = [
  string,
  number,
  string,
  [number, number],
  JourneyNode['kind'],
  string,
  string,
  Source[],
  string?,
  string?,
]

function journey(personId: string, introduction: string, stops: Stop[]): PersonJourney {
  return {
    personId,
    introduction,
    nodes: stops.map(
      ([
        key,
        year,
        location,
        coordinates,
        kind,
        title,
        summary,
        sources,
        dateNote,
        locationNote,
      ]) => ({
        id: `${personId}-record-${key}`,
        year,
        location,
        coordinates,
        kind,
        title,
        summary,
        sources,
        locationNote:
          locationNote ??
          '坐标为所述古城、山地或今城市附近的阅读参照，不代表古建筑边界或实际行路。',
        ...(dateNote ? { dateNote } : {}),
      }),
    ),
  }
}

