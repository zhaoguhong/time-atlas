function e(
  id: string,
  year: number,
  title: string,
  category: Category,
  themes: string[],
  place: EventDraft['place'],
  summary: string,
  text: string,
  impact: string,
  slug: string,
  people: string[] = [],
  extra: Partial<EventDraft> = {},
): EventDraft {
  return {
    id: `region-${id}`,
    year,
    title,
    category,
    themes,
    place,
    summary,
    text,
    impact,
    sources: [B(slug, title)],
    people,
    ...extra,
    ...(extra.endYear !== undefined && !extra.dateLabel
      ? { dateLabel: `${year}—${extra.endYear}年` }
      : {}),
    ...(extra.endYear !== undefined && !extra.dateNote
      ? {
          dateNote:
            '所标区间用于观察正文叙述的持续过程；其中各项活动并非同时发生，约略年代不作单年精确化。',
        }
      : {}),
  }
}
