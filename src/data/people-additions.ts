export function enrichAdditionalPeople(people: Person[]): Person[] {
  const result = [...people]
  for (const [rawId, name, era, role, biography, source] of rows) {
    const id = rawId
    const match = result.findIndex(
      (person) => person.name === name || person.aliases?.includes(name),
    )
    if (match >= 0) {
      const person = result[match]
      result[match] = {
        ...person,
        role,
        biography,
        summary: biography,
        recordKind: 'curated',
        sources: [book(source), ...person.sources],
      }
    } else
      result.push({
        id,
        name,
        era,
        role,
        biography,
        summary: biography,
        birth: null,
        death: null,
        color: '#798e7c',
        recordKind: 'curated',
        aliases: [name],
        sources: [book(source)],
      })
  }
  return result.map((person) => {
    const reviewed = reviewedDescriptions[person.name]
    return reviewed
      ? {
          ...person,
          ...reviewed,
          summary: reviewed.biography ?? person.summary,
          sources: [...(reviewed.sources ?? []), ...person.sources],
        }
      : person
  })
}
