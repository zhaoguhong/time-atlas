export function createReviewedEvents(people: Person[]): HistoryEvent[] {
  return reviewedEventDrafts.map(({ names, ...event }) => ({
    ...event,
    people: names.map((name) => {
      const person = people.find((person) => person.name === name || person.aliases?.includes(name))
      if (!person) throw new Error(`Reviewed event ${event.id}: missing person ${name}`)
      return person.id
    }),
  }))
}

