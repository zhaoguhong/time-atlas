function e(
  id: string,
  year: number,
  title: string,
  category: Category,
  location: string,
  coordinates: [number, number],
  summary: string,
  impact: string,
  people: string[],
  sources: Source[],
  importance = 3,
  notes?: { locationNote?: string; dateNote?: string },
): HistoryEvent {
  return {
    id,
    year,
    title,
    category,
    location,
    coordinates,
    summary,
    impact,
    people,
    sources,
    importance,
    background: eventBackgrounds[id] ?? summary,
    ...notes,
  }
}

