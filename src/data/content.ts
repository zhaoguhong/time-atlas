// Keep existing IDs and written biographies stable. Link imported identity facts
// through aliases as well as the display name (e.g. 杨广 / 隋炀帝).
const mergedPeople = new Map<string, Person>(
  [...corePeople, ...earlyPeople].map((person) => [
    person.id,
    { ...person, recordKind: 'curated' },
  ]),
)
for (const record of importedPeople) {
  const imported = record as Person
  const core = corePeople.find(
    (person) =>
      person.id === imported.id ||
      person.name === imported.name ||
      imported.aliases?.includes(person.name),
  )
  if (core) {
    mergedPeople.set(core.id, {
      ...imported,
      ...core,
      aliases: [...new Set([imported.name, ...(imported.aliases ?? [])])],
      recordKind: 'curated',
      sources: [...core.sources, ...imported.sources],
    })
  } else mergedPeople.set(imported.id, imported)
}
export const people: Person[] = enrichPersonReading(
  enrichDepthPeople(
    enrichReviewedPeople(
      enrichAdditionalPeople(
        [...mergedPeople.values()].map((person) => ({ ...person, ...personEnrichment[person.id] })),
      ),
    ),
  ),
).map((person) => ({ ...person, sources: canonicalSources(person.sources) }))

export const events: HistoryEvent[] = enrichEventReading(
  reviewEventRelations(
    [
      ...coreEvents,
      ...earlyEvents,
      ...civilizationEvents,
      ...createExpandedEvents(people),
      ...createReviewedEvents(people),
      ...createDepthEvents(people),
    ],
    people,
  ),
)
  .map((event) => ({ ...event, sources: canonicalSources(event.sources) }))
  .sort((a, b) => a.year - b.year)

export const eventById = new Map(events.map((event) => [event.id, event]))
export const personById = new Map(people.map((person) => [person.id, person]))
