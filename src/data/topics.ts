const original = (title: string): Source => ({
  title: `《${title}》· 专题相关本纪、列传与制度志`,
  url: bookUrl(title),
})
function topic(
  id: string,
  name: string,
  question: string,
  introduction: string[],
  conclusion: string,
  chapters: Chapter[],
  sources: Source[],
  color = '#71836b',
  icon: 'route' | 'swords' = 'route',
): Tour {
  return {
    id,
    name,
    question,
    introduction,
    conclusion,
    chapters: chapters.map(([eventId, explanation, mapReading]) => ({
      eventId,
      explanation,
      mapReading,
    })),
    steps: chapters.map(([id]) => id),
    sources,
    color,
    icon,
    subtitle: `${chapters.length} 章 · 地图与史事对读`,
    description: introduction[0],
  }
}
