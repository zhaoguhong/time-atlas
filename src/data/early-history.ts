// Approximate dates are explicit reading anchors, never invented exact-year claims.
function record(
  id: string,
  year: number,
  title: string,
  category: HistoryEvent['category'],
  location: string,
  coordinates: [number, number],
  summary: string,
  details: string,
  background: string,
  impact: string,
  sources: Source[],
  people: string[] = [],
  notes: Partial<HistoryEvent> = {},
): HistoryEvent {
  return {
    id,
    year,
    title,
    category,
    location,
    coordinates,
    summary,
    details: [details],
    background,
    impact,
    sources,
    people,
    importance: 4,
    locationNote: '标记为相关遗址或区域参照，不表示事件发生于一个可精确定位的点。',
    ...notes,
  }
}
