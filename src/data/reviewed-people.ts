export function enrichReviewedPeople(people: Person[]): Person[] {
  const records = [...people]
  for (const [name, role, biography] of introductions) {
    const index = records.findIndex(
      (person) => person.name === name || person.aliases?.includes(name),
    )
    const related = reviewedEventDrafts.filter((event) => event.names.includes(name))
    const sources = canonicalSources([
      ...new Map(
        related.flatMap((event) => event.sources).map((source) => [source.url, source]),
      ).values(),
    ])
    if (index >= 0) {
      records[index] = {
        ...records[index],
        role,
        summary: biography.split('。')[0] + '。',
        biography,
        recordKind: 'curated',
        sources: [...sources, ...records[index].sources],
      }
    } else {
      records.push({
        id: `reviewed-${name}`,
        name,
        role,
        summary: biography.split('。')[0] + '。',
        biography,
        recordKind: 'curated',
        birth: null,
        death: null,
        color: '#82916e',
        era: periodAt(related[0].year).id,
        sources,
      })
    }
  }
  return records.map((person) => {
    if (person.name === '孔子') return { ...person, death: -479 }
    if (person.name === '墨子') return { ...person, birth: null, death: null }
    if (person.name === '屈原') return { ...person, birth: null, death: null }
    if (person.name === '陶渊明') return { ...person, birth: null }
    if (person.name === '祖冲之') return { ...person, death: 500 }
    if (person.name === '建文帝')
      return {
        ...person,
        death: null,
        biography:
          '建文帝朱允炆是朱元璋之孙，1398年继位后试图削减宗室诸王的军事与地方力量。政策引起燕王朱棣起兵，双方经历多年的靖难战争。1402年南京陷落，建文帝失去皇位，其后的行踪和结局仍有争议，可靠材料不足以确定单一卒年。',
        sources: [book('明史', '4'), ...person.sources],
      }
    if (person.name === '李清照') return { ...person, death: null }
    return person
  })
}
