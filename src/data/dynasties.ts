import { earlyDynastySources } from './early-history'
import type { Dynasty, Source } from '../types'
import { dynastyReading } from './dynasty-reading'
const book = (name: string): Source => ({
  title: `《${name}》· 本纪与相关传记`,
  url: `https://zh.wikisource.org/wiki/${name}`,
  note: '存续纪年和简介为现代中文整理；导航分期与疆域数据的原始分组另行说明。',
})
function d(
  id: string,
  name: string,
  from: number,
  to: number,
  capital: string,
  summary: string,
  context: string,
  source: string,
  mapNames: string[],
  aliases: string[] = [],
  dateNote?: string,
): Dynasty {
  return {
    id,
    name,
    from,
    to,
    capital,
    summary,
    context,
    sources: earlyDynastySources[id] ?? [book(source)],
    mapNames:
      (
        {
          'shang-early': ['Shang Dynasty'],
          'western-zhou': ['Zhou Dynasty'],
          'eastern-zhou': ['Zhou Dynasty', 'Later Zhou'],
        } as Record<string, string[]>
      )[id] ?? mapNames,
    aliases: [name.replace(/朝$/, ''), ...aliases],
    ...(dateNote ? { dateNote } : {}),
  }
}
