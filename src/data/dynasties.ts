export const dynasties: Dynasty[] = dynastyRecords.map((dynasty) => ({
  ...dynasty,
  context: dynastyReading[dynasty.id][0],
  sections: dynastyReading[dynasty.id].slice(1).map((text) => ({
    title: '',
    text,
  })),
}))
export const dynastyById = new Map(dynasties.map((dynasty) => [dynasty.id, dynasty]))
export function dynastyForMap(name: string, year: number) {
  return dynasties.find(
    (dynasty) => dynasty.mapNames.includes(name) && dynasty.from <= year && dynasty.to >= year,
  )
}
