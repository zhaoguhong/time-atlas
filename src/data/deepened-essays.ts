export function deepenSelectedEssays(topics: Tour[]): Tour[] {
  return topics.map((topic) => {
    const revision = revisions[topic.id]
    if (!revision) return topic
    return {
      ...topic,
      introduction: revision.introduction,
      description: revision.introduction[0],
      conclusion: revision.conclusion,
      article: {
        paragraphs: revision.paragraphs,
        headings: revision.headings,
        eventIds: [...topic.steps],
        mapStops: revision.mapStops,
      },
      sources: canonicalSources([...(topic.sources ?? []), ...revision.sources]),
    }
  })
}
