  Partial<HistoryEvent>
function entry(record: Entry): HistoryEvent {
  return {
    category: '文化',
    region: 'china',
    importance: 4,
    themes: ['哲学', '教育学术'],
    locationNote:
      '坐标为所述思想、著述或学术传统的地域阅读参照；不能据此证明作者在某年到访，也不构成人物年谱。',
    ...record,
  }
}

